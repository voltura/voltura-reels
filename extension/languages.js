export function resolveLanguage(preference, browserLanguages = navigator.languages) {
  if (languages.some((item) => item.code === preference)) return preference;
  for (const locale of browserLanguages) {
    const code = locale.toLowerCase().replaceAll('_', '-');
    const [base] = code.split('-');
    let match = base;
    if (base === 'pt') match = code === 'pt-pt' ? 'pt-PT' : 'pt-BR';
    if (base === 'no') match = 'nb';
    if (base === 'zh')
      match = /^(zh$|zh-hant\b|zh-(tw|hk|mo)\b)/.test(code) && !code.includes('hans') ? 'zh-TW' : '';
    if (languages.some((item) => item.code === match)) return match;
  }
  return 'en';
}

